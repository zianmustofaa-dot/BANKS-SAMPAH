DROP VIEW  IF EXISTS v_riwayat_setoran CASCADE;
DROP VIEW  IF EXISTS v_rekap_kategori  CASCADE;
DROP VIEW  IF EXISTS v_saldo_nasabah   CASCADE;
DROP TABLE IF EXISTS penarikan_saldo   CASCADE;
DROP TABLE IF EXISTS detail_setoran    CASCADE;
DROP TABLE IF EXISTS setoran           CASCADE;
DROP TABLE IF EXISTS petugas           CASCADE;
DROP TABLE IF EXISTS nasabah           CASCADE;
DROP TABLE IF EXISTS jenis_sampah      CASCADE;
DROP TABLE IF EXISTS kategori_sampah   CASCADE;

-- ------------------------------------------------------------
-- 1. TABEL MASTER
-- ------------------------------------------------------------
CREATE TABLE kategori_sampah (
    id_kategori   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kategori VARCHAR(50)  NOT NULL UNIQUE,
    deskripsi     VARCHAR(150)
);
COMMENT ON TABLE kategori_sampah IS 'Daftar kategori sampah daur ulang';

CREATE TABLE jenis_sampah (
    id_jenis     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_kategori  INTEGER NOT NULL,
    nama_jenis   VARCHAR(80) NOT NULL UNIQUE,
    harga_per_kg NUMERIC(10,2) NOT NULL CHECK (harga_per_kg >= 0),
    CONSTRAINT fk_jenis_kategori FOREIGN KEY (id_kategori)
        REFERENCES kategori_sampah(id_kategori)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
COMMENT ON TABLE jenis_sampah IS 'Jenis sampah dan harga beli per kilogram';

CREATE TABLE nasabah (
    id_nasabah INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama       VARCHAR(100) NOT NULL,
    alamat     VARCHAR(200),
    no_hp      VARCHAR(15) UNIQUE,
    tgl_daftar DATE NOT NULL
);
COMMENT ON TABLE nasabah IS 'Nasabah bank sampah';

CREATE TABLE petugas (
    id_petugas   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_petugas VARCHAR(100) NOT NULL,
    jabatan      VARCHAR(50),
    no_hp        VARCHAR(15) UNIQUE
);
COMMENT ON TABLE petugas IS 'Petugas operasional bank sampah';

-- ------------------------------------------------------------
-- 2. TABEL TRANSAKSI
-- ------------------------------------------------------------
CREATE TABLE setoran (
    id_setoran  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nasabah  INTEGER NOT NULL,
    id_petugas  INTEGER NOT NULL,
    tgl_setoran DATE NOT NULL,
    catatan     VARCHAR(150),
    CONSTRAINT fk_setoran_nasabah FOREIGN KEY (id_nasabah)
        REFERENCES nasabah(id_nasabah) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_setoran_petugas FOREIGN KEY (id_petugas)
        REFERENCES petugas(id_petugas) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_setoran_tgl ON setoran(tgl_setoran);
COMMENT ON TABLE setoran IS 'Header transaksi setoran sampah';

CREATE TABLE detail_setoran (
    id_detail    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_setoran   INTEGER NOT NULL,
    id_jenis     INTEGER NOT NULL,
    berat_kg     NUMERIC(8,2)  NOT NULL CHECK (berat_kg > 0),
    harga_satuan NUMERIC(10,2) NOT NULL CHECK (harga_satuan > 0),
    CONSTRAINT fk_detail_setoran FOREIGN KEY (id_setoran)
        REFERENCES setoran(id_setoran) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_detail_jenis FOREIGN KEY (id_jenis)
        REFERENCES jenis_sampah(id_jenis) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_detail_setoran ON detail_setoran(id_setoran);
COMMENT ON COLUMN detail_setoran.harga_satuan IS 'Snapshot harga saat transaksi (harga master bisa berubah)';

CREATE TABLE penarikan_saldo (
    id_penarikan  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_nasabah    INTEGER NOT NULL,
    id_petugas    INTEGER NOT NULL,
    tgl_penarikan DATE NOT NULL,
    jumlah        NUMERIC(12,2) NOT NULL CHECK (jumlah > 0),
    CONSTRAINT fk_tarik_nasabah FOREIGN KEY (id_nasabah)
        REFERENCES nasabah(id_nasabah) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_tarik_petugas FOREIGN KEY (id_petugas)
        REFERENCES petugas(id_petugas) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_tarik_tgl ON penarikan_saldo(tgl_penarikan);
COMMENT ON TABLE penarikan_saldo IS 'Transaksi penarikan saldo nasabah';

-- ------------------------------------------------------------
-- 3. TRIGGER PELINDUNG SALDO
--    Penarikan ditolak bila melebihi saldo tersedia.
--    Saldo = total setoran - total penarikan yang sudah ada.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_cek_saldo_penarikan() RETURNS TRIGGER AS $$
DECLARE
    saldo_ada NUMERIC(14,2);
BEGIN
    SELECT
        COALESCE((SELECT SUM(d.berat_kg * d.harga_satuan)
                  FROM setoran st
                  JOIN detail_setoran d ON st.id_setoran = d.id_setoran
                  WHERE st.id_nasabah = NEW.id_nasabah), 0)
      - COALESCE((SELECT SUM(jumlah)
                  FROM penarikan_saldo
                  WHERE id_nasabah = NEW.id_nasabah), 0)
    INTO saldo_ada;

    IF NEW.jumlah > saldo_ada THEN
        RAISE EXCEPTION 'PENARIKAN DITOLAK: saldo tidak mencukupi (tersedia %)', saldo_ada
            USING ERRCODE = '45000';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_penarikan_cek_saldo
    BEFORE INSERT ON penarikan_saldo
    FOR EACH ROW EXECUTE FUNCTION fn_cek_saldo_penarikan();

-- ------------------------------------------------------------
-- 4. VIEW REKAPITULASI
-- ------------------------------------------------------------
-- Saldo tiap nasabah: total setoran - total penarikan
CREATE VIEW v_saldo_nasabah AS
SELECT n.id_nasabah,
       n.nama,
       n.no_hp,
       COALESCE(s.total_setor, 0)                       AS total_setor,
       COALESCE(t.total_tarik, 0)                       AS total_tarik,
       COALESCE(s.total_setor, 0) - COALESCE(t.total_tarik, 0) AS saldo
FROM nasabah n
LEFT JOIN (
    SELECT st.id_nasabah, SUM(d.berat_kg * d.harga_satuan) AS total_setor
    FROM setoran st
    JOIN detail_setoran d ON st.id_setoran = d.id_setoran
    GROUP BY st.id_nasabah
) s ON n.id_nasabah = s.id_nasabah
LEFT JOIN (
    SELECT id_nasabah, SUM(jumlah) AS total_tarik
    FROM penarikan_saldo
    GROUP BY id_nasabah
) t ON n.id_nasabah = t.id_nasabah;

-- Total berat & nilai per kategori
CREATE VIEW v_rekap_kategori AS
SELECT k.id_kategori,
       k.nama_kategori,
       SUM(d.berat_kg)                 AS total_kg,
       SUM(d.berat_kg * d.harga_satuan) AS total_nilai
FROM detail_setoran d
JOIN jenis_sampah j    ON d.id_jenis    = j.id_jenis
JOIN kategori_sampah k ON j.id_kategori = k.id_kategori
GROUP BY k.id_kategori, k.nama_kategori;

-- Riwayat lengkap baris setoran (setoran x nasabah x petugas x jenis x kategori)
CREATE VIEW v_riwayat_setoran AS
SELECT s.id_setoran,
       s.tgl_setoran,
       n.id_nasabah,
       n.nama AS nasabah,
       p.nama_petugas AS petugas,
       k.nama_kategori,
       j.nama_jenis,
       d.berat_kg,
       d.harga_satuan,
       d.berat_kg * d.harga_satuan AS subtotal
FROM detail_setoran d
JOIN setoran s         ON d.id_setoran  = s.id_setoran
JOIN nasabah n         ON s.id_nasabah  = n.id_nasabah
JOIN petugas p         ON s.id_petugas  = p.id_petugas
JOIN jenis_sampah j    ON d.id_jenis    = j.id_jenis
JOIN kategori_sampah k ON j.id_kategori = k.id_kategori;
