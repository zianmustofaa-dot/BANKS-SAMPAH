-- Target deployment: PostgreSQL 17 (Neon Serverless Postgres)
-- Struktur, relasi, constraint, view, dan trigger mengikuti
-- hasil perancangan Tugas 1 (PDM 7 tabel) dengan penyesuaian
-- tipe data PostgreSQL.
